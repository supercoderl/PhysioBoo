// Regenerates src/app/shared/icons/icon-names.ts from the SVG files in src/assets/icons.
// Runs before start / build / watch / test (see package.json), so dropping an SVG into the folder is enough.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'src/assets/icons');
const outFile = join(root, 'src/app/shared/icons/icon-names.ts');

const names = readdirSync(iconsDir)
    .filter((file) => file.toLowerCase().endsWith('.svg'))
    .map((file) => file.slice(0, -4))
    .sort();

const content = [
    '/**',
    ' * Every icon shipped in `src/assets/icons` (file name without `.svg`).',
    ' * Generated by `scripts/generate-icon-names.mjs` before start/build; do not edit by hand.',
    ' */',
    'export const PHYSIO_ICON_NAMES: readonly string[] = [',
    ...names.map((name) => `    '${name}',`),
    '];',
    '',
].join('\n');

let current = '';
try { current = readFileSync(outFile, 'utf8'); } catch { /* first run */ }

if (current !== content) {
    writeFileSync(outFile, content);
    console.log(`[icons] icon-names.ts updated (${names.length} icons)`);
}
